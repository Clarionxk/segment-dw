"""
core/parser.py — Robust Markdown parser for extracting video download targets and segments.

Supports multiple Markdown formats commonly generated by AI agents and humans:
  1. Markdown Tables (| Title | URL | Start | End | Resolution |)
  2. Structured Key-Value List Blocks (- URL: ... / - Start: ... / - End: ...)
  3. Inline Markdown Links (- [Title](URL) (Start - End) [Res])
  4. Delimited Inline Items (- URL | Start - End | Title)
  5. Embedded JSON / Code Blocks
  6. Freeform lines containing YouTube URLs and timestamp ranges
"""

import re
import json
from dataclasses import dataclass, field
from typing import List, Optional, Tuple


@dataclass
class PlanItem:
    url: str
    title: Optional[str] = None
    start: Optional[str] = None
    end: Optional[str] = None
    resolution: Optional[str] = None
    raw_source: str = ""

    def to_dict(self) -> dict:
        return {
            "title": self.title,
            "url": self.url,
            "start": self.start,
            "end": self.end,
            "resolution": self.resolution,
        }


# YouTube URL Regex Patterns
YT_URL_REGEX = re.compile(
    r"https?://(?:(?:www\.|m\.)?youtube\.com/(?:watch\?[^\s\)\"\]]+|shorts/[a-zA-Z0-9_-]+|live/[a-zA-Z0-9_-]+|embed/[a-zA-Z0-9_-]+)|youtu\.be/[a-zA-Z0-9_-]+[^\s\)\"\]]*)",
    re.IGNORECASE,
)

# Timestamp Regex (matches MM:SS, HH:MM:SS, or raw seconds)
TIMESTAMP_TOKEN = r"(?:\d{1,2}:)?\d{1,2}:\d{2}(?:\.\d+)?|\b\d+(?:\.\d+)?s?\b"
TIMESTAMP_RANGE_REGEX = re.compile(
    r"(?:(?:from|start|in)?\s*[\(\[\{]?)(" + TIMESTAMP_TOKEN + r")\s*(?:-|–|—|to)\s*(" + TIMESTAMP_TOKEN + r")[\)\]\}]?",
    re.IGNORECASE,
)

# Resolution Regex
RESOLUTION_REGEX = re.compile(
    r"\b(2160p|4k|1440p|2k|1080p|720p|480p|360p|240p|best)\b",
    re.IGNORECASE,
)


def _clean_url(url: str) -> str:
    """Strip trailing markdown brackets, punctuation, or unwanted query characters."""
    url = url.strip()
    # Strip common markdown closing delimiters
    url = re.sub(r"[\)\]\}\>\"\']+$", "", url)
    url = re.sub(r"[,;.]+$", "", url)
    return url


def _clean_time_str(time_val: Optional[str]) -> Optional[str]:
    """Clean timestamp value, stripping 's' or whitespace."""
    if not time_val:
        return None
    time_val = str(time_val).strip()
    if not time_val or time_val.lower() in ("none", "-", "null", "n/a", "end", "start"):
        return None
    time_val = re.sub(r"[sS]$", "", time_val).strip()
    return time_val


def _clean_title(title: Optional[str]) -> Optional[str]:
    """Clean title text, stripping markdown bold/italic and leading bullets/numbers."""
    if not title:
        return None
    t = title.strip()
    # Remove markdown bold/italic
    t = re.sub(r"^[\*\_#\-\s\d\.]+", "", t)
    t = re.sub(r"[\*\_]+", "", t)
    t = t.strip()
    return t or None


def _clean_resolution(res: Optional[str]) -> Optional[str]:
    if not res:
        return None
    match = RESOLUTION_REGEX.search(res)
    if match:
        val = match.group(1).lower()
        if val == "4k":
            return "2160p"
        if val == "2k":
            return "1440p"
        return val
    return None


# ---------------------------------------------------------------------------
# Strategy 1: JSON Code Blocks
# ---------------------------------------------------------------------------

def _parse_json_blocks(markdown_text: str) -> List[PlanItem]:
    items: List[PlanItem] = []
    # Find ```json ... ``` blocks
    code_blocks = re.findall(r"```(?:json)?\s*([\s\S]*?)```", markdown_text, re.IGNORECASE)
    for block in code_blocks:
        block = block.strip()
        if not block.startswith(("[", "{")):
            continue
        try:
            data = json.loads(block)
            if isinstance(data, dict):
                data = [data]
            if isinstance(data, list):
                for obj in data:
                    if not isinstance(obj, dict):
                        continue
                    url = obj.get("url") or obj.get("link") or obj.get("video")
                    if url and YT_URL_REGEX.search(str(url)):
                        items.append(
                            PlanItem(
                                url=_clean_url(str(url)),
                                title=_clean_title(obj.get("title") or obj.get("name") or obj.get("clip")),
                                start=_clean_time_str(obj.get("start") or obj.get("from")),
                                end=_clean_time_str(obj.get("end") or obj.get("to")),
                                resolution=_clean_resolution(obj.get("resolution") or obj.get("res")),
                                raw_source=json.dumps(obj),
                            )
                        )
        except Exception:
            continue
    return items


# ---------------------------------------------------------------------------
# Strategy 2: Markdown Tables
# ---------------------------------------------------------------------------

def _parse_markdown_tables(markdown_text: str) -> List[PlanItem]:
    items: List[PlanItem] = []
    lines = markdown_text.splitlines()

    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("|") and line.endswith("|"):
            # Potential table header
            header_cells = [c.strip().lower() for c in line.strip("|").split("|")]
            
            # Identify column mappings
            url_idx = -1
            title_idx = -1
            start_idx = -1
            end_idx = -1
            res_idx = -1
            timestamps_idx = -1

            for idx, col in enumerate(header_cells):
                col_name = col.replace(" ", "").replace("_", "")
                if col_name in ("url", "link", "video", "videourl", "youtube", "sourcelink"):
                    url_idx = idx
                elif col_name in ("title", "name", "clip", "game", "segment", "description", "target"):
                    title_idx = idx
                elif col_name in ("start", "starttimes", "from", "in", "starttime"):
                    start_idx = idx
                elif col_name in ("end", "endtimes", "to", "out", "endtime", "stop"):
                    end_idx = idx
                elif col_name in ("timestamps", "timestamp", "timerange", "range", "cliprange"):
                    timestamps_idx = idx
                elif col_name in ("res", "resolution", "quality", "format"):
                    res_idx = idx

            # If no URL column found, check if this is a table without standard headers
            if i + 1 < len(lines) and re.match(r"^\|?\s*[-:]+[-| :]*\|?$", lines[i + 1].strip()):
                # Valid markdown table divider
                i += 2  # Skip header & separator
                while i < len(lines):
                    row_line = lines[i].strip()
                    if not (row_line.startswith("|") and row_line.endswith("|")):
                        break
                    row_cells = [c.strip() for c in row_line.strip("|").split("|")]
                    
                    found_url = None
                    if url_idx != -1 and url_idx < len(row_cells):
                        m = YT_URL_REGEX.search(row_cells[url_idx])
                        if m:
                            found_url = _clean_url(m.group(0))
                    
                    # If url_idx didn't find one, scan all cells for a YouTube URL
                    if not found_url:
                        for cell in row_cells:
                            m = YT_URL_REGEX.search(cell)
                            if m:
                                found_url = _clean_url(m.group(0))
                                break

                    if found_url:
                        row_title = row_cells[title_idx] if (title_idx != -1 and title_idx < len(row_cells)) else None
                        row_start = row_cells[start_idx] if (start_idx != -1 and start_idx < len(row_cells)) else None
                        row_end = row_cells[end_idx] if (end_idx != -1 and end_idx < len(row_cells)) else None
                        row_res = row_cells[res_idx] if (res_idx != -1 and res_idx < len(row_cells)) else None

                        # If there is a combined timestamps column
                        if (not row_start or not row_end) and timestamps_idx != -1 and timestamps_idx < len(row_cells):
                            ts_cell = row_cells[timestamps_idx]
                            range_m = TIMESTAMP_RANGE_REGEX.search(ts_cell)
                            if range_m:
                                row_start = row_start or range_m.group(1)
                                row_end = row_end or range_m.group(2)

                        items.append(
                            PlanItem(
                                url=found_url,
                                title=_clean_title(row_title),
                                start=_clean_time_str(row_start),
                                end=_clean_time_str(row_end),
                                resolution=_clean_resolution(row_res),
                                raw_source=row_line,
                            )
                        )
                    i += 1
                continue
        i += 1

    return items


# ---------------------------------------------------------------------------
# Strategy 3: Key-Value List / Headings Block
# ---------------------------------------------------------------------------

def _parse_key_value_blocks(markdown_text: str) -> List[PlanItem]:
    items: List[PlanItem] = []
    lines = markdown_text.splitlines()

    current_title: Optional[str] = None
    current_url: Optional[str] = None
    current_start: Optional[str] = None
    current_end: Optional[str] = None
    current_res: Optional[str] = None
    block_lines: List[str] = []

    def flush_block():
        nonlocal current_title, current_url, current_start, current_end, current_res, block_lines
        if current_url:
            items.append(
                PlanItem(
                    url=current_url,
                    title=_clean_title(current_title),
                    start=_clean_time_str(current_start),
                    end=_clean_time_str(current_end),
                    resolution=_clean_resolution(current_res),
                    raw_source="\n".join(block_lines),
                )
            )
        current_title = None
        current_url = None
        current_start = None
        current_end = None
        current_res = None
        block_lines = []

    for line in lines:
        stripped = line.strip()

        # Check for heading (e.g. ## 1. Half Life 2 or ### Game: Doom 3)
        heading_match = re.match(r"^#{1,6}\s*(.*)", stripped)
        if heading_match:
            flush_block()
            current_title = heading_match.group(1).strip()
            block_lines.append(stripped)
            continue

        # Check for key-value pair, e.g. - URL: ..., * Start: ..., End: ...
        kv_match = re.match(
            r"^(?:[-*+]|\d+\.)?\s*\*{0,2}(url|link|video|title|name|clip|start|begin|end|to|stop|res|resolution|timestamps?)\*{0,2}\s*[:=-]\s*(.*)",
            stripped,
            re.IGNORECASE,
        )
        if kv_match:
            key = kv_match.group(1).lower()
            val = kv_match.group(2).strip()
            block_lines.append(stripped)

            if key in ("url", "link", "video"):
                m_url = YT_URL_REGEX.search(val)
                if m_url:
                    current_url = _clean_url(m_url.group(0))
                else:
                    current_url = _clean_url(val)
            elif key in ("title", "name", "clip"):
                current_title = val
            elif key in ("start", "begin"):
                current_start = val
            elif key in ("end", "to", "stop"):
                current_end = val
            elif key in ("res", "resolution"):
                current_res = val
            elif key in ("timestamp", "timestamps"):
                range_m = TIMESTAMP_RANGE_REGEX.search(val)
                if range_m:
                    current_start = range_m.group(1)
                    current_end = range_m.group(2)
            continue

        # If empty line or separator line, flush block if we already have an item
        if stripped == "" or stripped.startswith("---") or stripped.startswith("___"):
            flush_block()

    flush_block()
    return items


# ---------------------------------------------------------------------------
# Strategy 4 & 5: Inline Links, Bullets & Freeform Lines
# ---------------------------------------------------------------------------

def _parse_inline_lines(markdown_text: str) -> List[PlanItem]:
    items: List[PlanItem] = []
    lines = markdown_text.splitlines()

    for line in lines:
        stripped = line.strip()
        # Skip table rows and pure headings
        if stripped.startswith("|") and stripped.endswith("|"):
            continue
        if stripped.startswith("#"):
            continue

        m_url = YT_URL_REGEX.search(stripped)
        if not m_url:
            continue

        url = _clean_url(m_url.group(0))
        
        # Look for markdown link pattern [Title](URL)
        link_match = re.search(r"\[([^\]]+)\]\((https?://[^\)]+)\)", stripped)
        title = None
        if link_match:
            title = link_match.group(1)

        # Look for timestamp range
        start = None
        end = None
        range_match = TIMESTAMP_RANGE_REGEX.search(stripped)
        if range_match:
            start = range_match.group(1)
            end = range_match.group(2)
        else:
            # Single timestamp check (e.g. from 01:20)
            single_start = re.search(rf"\b(?:from|start|in)\s+({TIMESTAMP_TOKEN})", stripped, re.IGNORECASE)
            if single_start:
                start = single_start.group(1)
            single_end = re.search(rf"\b(?:to|until|out)\s+({TIMESTAMP_TOKEN})", stripped, re.IGNORECASE)
            if single_end:
                end = single_end.group(1)

        # Look for resolution
        res = _clean_resolution(stripped)

        # If title wasn't found from markdown link, attempt to extract prefix or suffix
        if not title:
            # Check pattern: - Title: URL (timestamps)
            prefix_match = re.match(r"^(?:[-*+]|\d+\.)?\s*(.*?)(?::\s*http|\|\s*http|\s*-\s*http)", stripped)
            if prefix_match:
                candidate_title = prefix_match.group(1).strip()
                if candidate_title and not candidate_title.lower().startswith(("url", "link", "video", "http")):
                    title = candidate_title

        # Check pattern: URL | 01:20 - 02:45 | Title
        if not title and "|" in stripped:
            parts = [p.strip() for p in stripped.split("|")]
            for p in parts:
                if not YT_URL_REGEX.search(p) and not TIMESTAMP_RANGE_REGEX.search(p) and not RESOLUTION_REGEX.search(p):
                    if len(p) > 1:
                        title = p
                        break

        items.append(
            PlanItem(
                url=url,
                title=_clean_title(title),
                start=_clean_time_str(start),
                end=_clean_time_str(end),
                resolution=res,
                raw_source=stripped,
            )
        )

    return items


# ---------------------------------------------------------------------------
# Master Parser Entry Point
# ---------------------------------------------------------------------------

def parse_markdown_plan(markdown_text: str) -> List[PlanItem]:
    """
    Parse a Markdown document and return a list of PlanItem video/segment targets.
    Automatically identifies and uses the best matching strategies (JSON code blocks,
    Markdown tables, Key-Value blocks, or inline bullet links).
    """
    # 1. First try JSON code blocks
    json_items = _parse_json_blocks(markdown_text)
    if json_items:
        return json_items

    # 2. Try Markdown tables
    table_items = _parse_markdown_tables(markdown_text)
    if table_items:
        return table_items

    # 3. Try Key-Value list blocks
    kv_items = _parse_key_value_blocks(markdown_text)
    if kv_items:
        return kv_items

    # 4. Fallback to inline links & freeform lines
    inline_items = _parse_inline_lines(markdown_text)
    
    # Deduplicate while preserving order
    seen = set()
    deduped: List[PlanItem] = []
    for item in inline_items:
        key = (item.url, item.start, item.end, item.title)
        if key not in seen:
            seen.add(key)
            deduped.append(item)

    return deduped
